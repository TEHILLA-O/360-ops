import { useMemo, useState } from "react";
import { useQuery } from "@tanstack/react-query";
import { api, ApiError } from "../api";
import { formatWhen, words } from "../lib/format";
import { useSession } from "../session";
import type { CaseEvent } from "../types";

export function AuditView() {
  const { personaId } = useSession();
  const [query, setQuery] = useState("");
  const [action, setAction] = useState("");
  const audit = useQuery({
    queryKey: ["audit", personaId],
    queryFn: () => api<CaseEvent[]>("/api/audit", personaId),
  });
  const rows = useMemo(() => {
    return (audit.data || []).filter((event) => {
      const hay = `${event.action} ${event.actor_id || ""} ${event.case_id || ""} ${event.reason || ""}`.toLowerCase();
      if (query && !hay.includes(query.trim().toLowerCase())) return false;
      if (action && event.action !== action) return false;
      return true;
    });
  }, [action, audit.data, query]);
  if (audit.isError) {
    return <p className="text-sm text-slate">{audit.error instanceof ApiError ? audit.error.message : "Audit is not available to this persona."}</p>;
  }
  const actions = [...new Set((audit.data || []).map((event) => event.action))].sort();
  return (
    <div className="space-y-4">
      <header className="flex flex-wrap items-end justify-between gap-3">
        <div>
          <div className="kicker">Audit explorer</div>
          <h2 className="text-2xl">Append-only evidence</h2>
        </div>
      </header>
      <p className="text-xs text-slate">Exports are generated by the case service and include the generation time and evidence source.</p>
      <div className="flex gap-2">
        <button className="border border-ink/15 px-3 py-2 text-sm" onClick={() => download("csv", personaId)}>Download CSV</button>
        <button className="border border-ink/15 px-3 py-2 text-sm" onClick={() => download("json", personaId)}>Download JSON</button>
        <button className="border border-ink/15 px-3 py-2 text-sm" onClick={() => download("pdf", personaId)}>Download PDF</button>
      </div>
      <div className="flex flex-wrap gap-2">
        <input value={query} onChange={(event) => setQuery(event.target.value)} placeholder="Search actor, case, reason" className="border border-ink/10 bg-white px-3 py-2 text-sm" />
        <select value={action} onChange={(event) => setAction(event.target.value)} className="border border-ink/10 bg-white px-3 py-2 text-sm" aria-label="Event type">
          <option value="">All events</option>
          {actions.map((item) => <option key={item} value={item}>{words(item)}</option>)}
        </select>
      </div>
      <div className="overflow-auto border border-ink/10 bg-white">
        <table className="w-full min-w-[860px] text-left text-sm">
          <thead className="text-xs uppercase tracking-wide text-slate">
            <tr>
              <th className="px-3 py-2">When</th>
              <th className="px-3 py-2">Action</th>
              <th className="px-3 py-2">Actor</th>
              <th className="px-3 py-2">From</th>
              <th className="px-3 py-2">To</th>
              <th className="px-3 py-2">Source</th>
              <th className="px-3 py-2">Reason</th>
            </tr>
          </thead>
          <tbody>
            {rows.slice(0, 80).map((event) => (
              <tr key={event.id} className="border-t border-ink/5 align-top">
                <td className="num px-3 py-2">{formatWhen(event.occurred_at)}</td>
                <td className="px-3 py-2">{words(event.action)}</td>
                <td className="px-3 py-2">{event.actor_id || "—"}</td>
                <td className="px-3 py-2">{words(event.previous_state)}</td>
                <td className="px-3 py-2">{words(event.new_state)}</td>
                <td className="px-3 py-2">{event.source_system}</td>
                <td className="px-3 py-2">{event.reason}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
}

async function download(format: string, personaId: string) {
  const response = await fetch(`/api/audit/export?export_format=${format}`, { headers: { "X-OpsPilot-Actor": personaId } });
  const blob = await response.blob();
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = `opspilot-audit.${format === "pdf" ? "pdf" : format}`;
  anchor.click();
  URL.revokeObjectURL(url);
}
